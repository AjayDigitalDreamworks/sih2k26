/**
 * Get dense road coordinates for a corridor between any two NER districts.
 * If direct leg is cached, returns it. If multi-leg corridor, combines legs.
 * Never returns a 2-point straight line when hub coordinates can be bridged.
 */
export function getCorridorRoadCoordinates(fromId, toId) {
  if (!fromId || !toId || fromId === toId) return [];
  const key = `${fromId}-${toId}`;
  if (CORRIDOR_ROAD_GEOMETRIES[key]?.coords?.length) {
    return CORRIDOR_ROAD_GEOMETRIES[key].coords;
  }

  // Common multi-hop junctions in NER network
  // Kamrup -> Aizawl = Kamrup -> East Khasi -> Cachar -> Aizawl
  if (fromId === 'kamrup' && toId === 'aizawl') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['kamrup-east_khasi']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['east_khasi-cachar']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['cachar-aizawl']?.coords || []),
    ];
  }
  if (fromId === 'aizawl' && toId === 'kamrup') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['aizawl-cachar']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['cachar-east_khasi']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['east_khasi-kamrup']?.coords || []),
    ];
  }

  // Kamrup -> Kohima = Kamrup -> Dimapur -> Kohima
  if (fromId === 'kamrup' && toId === 'kohima') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['kamrup-dimapur']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['dimapur-kohima']?.coords || []),
    ];
  }
  if (fromId === 'kohima' && toId === 'kamrup') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['kohima-dimapur']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['dimapur-kamrup']?.coords || []),
    ];
  }

  // Kamrup -> Imphal West = Kamrup -> Dimapur -> Kohima -> Imphal West
  if (fromId === 'kamrup' && toId === 'imphal_west') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['kamrup-dimapur']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['dimapur-kohima']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['kohima-imphal_west']?.coords || []),
    ];
  }
  if (fromId === 'imphal_west' && toId === 'kamrup') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['imphal_west-kohima']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['kohima-dimapur']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['dimapur-kamrup']?.coords || []),
    ];
  }

  // Kamrup -> Cachar = Kamrup -> East Khasi -> Cachar
  if (fromId === 'kamrup' && toId === 'cachar') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['kamrup-east_khasi']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['east_khasi-cachar']?.coords || []),
    ];
  }
  if (fromId === 'cachar' && toId === 'kamrup') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['cachar-east_khasi']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['east_khasi-kamrup']?.coords || []),
    ];
  }

  // Kamrup -> West Tripura = Kamrup -> East Khasi -> Cachar -> West Tripura
  if (fromId === 'kamrup' && toId === 'west_tripura') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['kamrup-east_khasi']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['east_khasi-cachar']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['cachar-west_tripura']?.coords || []),
    ];
  }
  if (fromId === 'west_tripura' && toId === 'kamrup') {
    return [
      ...(CORRIDOR_ROAD_GEOMETRIES['west_tripura-cachar']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['cachar-east_khasi']?.coords || []),
      ...(CORRIDOR_ROAD_GEOMETRIES['east_khasi-kamrup']?.coords || []),
    ];
  }

  return [];
}

export default {
  CORRIDOR_ROAD_GEOMETRIES,
  getCorridorRoadCoordinates,
};
