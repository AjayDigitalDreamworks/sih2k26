const DICT_BY_VALUE = {};
Object.keys(DICT).forEach((langCode) => {
  DICT_BY_VALUE[langCode] = {};
  if (DICT.en) {
    Object.keys(DICT.en).forEach((key) => {
      const enVal = DICT.en[key];
      const transVal = DICT[langCode]?.[key];
      if (enVal && transVal) {
        DICT_BY_VALUE[langCode][enVal] = transVal;
      }
    });
  }
});

