/** Translate alert title, message, and severity to active language */
export const localizeAlert = (alert, lang = 'en') => {
  if (!alert) return alert;
  if (!lang || lang === 'en') return alert;

  const dict = ALERT_TERMS[lang] || ALERT_TERMS.en;
  let title = alert.title || '';
  let message = alert.message || '';
  let severity = alert.severity || '';

  const rawSev = String(severity).toLowerCase();
  if (rawSev === 'high' && dict['High']) severity = dict['High'];
  else if (rawSev === 'critical' && dict['Critical']) severity = dict['Critical'];
  else if (rawSev === 'medium' && dict['Medium']) severity = dict['Medium'];
  else if (rawSev === 'low' && dict['Low']) severity = dict['Low'];

  Object.keys(ALERT_TERMS.en).forEach((enTerm) => {
    const localized = dict[enTerm];
    if (localized && localized !== enTerm) {
      const regex = new RegExp(enTerm, 'gi');
      title = title.replace(regex, localized);
      message = message.replace(regex, localized);
    }
  });

  return {
    ...alert,
    title,
    message,
    severity,
  };
};

const LanguageContext = createContext(undefined);

export const LanguageProvider = ({ children }) => {
  const [lang, setLangState] = useState(() => {
    try {
      return localStorage.getItem("raahi_lang") || "en";
    } catch {
      return "en";
    }
  });

  useEffect(() => {
    try {
      localStorage.setItem("raahi_lang", lang);
    } catch { /* storage unavailable */ }
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = (code) => {
    const c = DICT[code] ? code : "en";
    setLangState(c);
  };

  const t = (key) => {
    if (!key || typeof key !== 'string') return key;
    const table = DICT[lang] || DICT.en;
    if (table[key] !== undefined) return table[key];
    if (DICT.en[key] !== undefined) return DICT.en[key];
    if (DICT_BY_VALUE[lang]?.[key]) return DICT_BY_VALUE[lang][key];
    return key;
  };

  return (
    <LanguageContext.Provider value={{ lang, setLang, t, LANGUAGES, localizeAlert }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLang = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLang must be used inside LanguageProvider");
  return ctx;
};

export default LanguageProvider;